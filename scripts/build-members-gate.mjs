/**
 * Writes worker/members-gate.js: the members gate of a hosted site as one
 * text the service can upload (worker/hosting.js).
 *
 * The text is worker/members-gate-entry.js bundled with the files it imports
 * from templates/functions/, so the gate on Kiln's hosting and the gate on
 * Cloudflare Pages are the same code. `npm run build` runs this after the
 * editor's build, and so does `node scripts/build-members-gate.mjs`. A test (test/hosting-members.test.js)
 * fails when the written file is older than its sources.
 */
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'worker/members-gate.js');

/** The Worker module's text, bundled fresh from the sources. */
export async function gateModuleText() {
  const out = await build({
    absWorkingDir: ROOT,
    entryPoints: ['worker/members-gate-entry.js'],
    bundle: true, format: 'esm', target: 'es2022', platform: 'neutral',
    write: false, minify: false, legalComments: 'none', charset: 'utf8', logLevel: 'silent',
  });
  return out.outputFiles[0].text;
}

/** The whole of worker/members-gate.js for that text. */
export function gateFile(text) {
  return [
    '// GENERATED by scripts/build-members-gate.mjs from worker/members-gate-entry.js and',
    '// templates/functions/. Do not edit this file: change those, then run `npm run build`.',
    `export const MEMBERS_GATE_MODULE = ${JSON.stringify(text)};`,
    '',
  ].join('\n');
}

export async function writeGateModule() {
  await writeFile(OUT, gateFile(await gateModuleText()));
  return OUT;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`wrote ${await writeGateModule()}`);
}
